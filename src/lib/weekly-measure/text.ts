// Вывод замера человеческим текстом (этап 87): владелец читает ответы, а не SQL, и ничего не считает в голове.
// Здесь только текст из уже посчитанного замера: чистые функции, их проверяют модульные тесты.

import type { DetailsVerdict, Move, MoveFlag, MoveReason, Survey } from "./survey";

const pct = (share: number): string => `${Math.round(share * 100)}%`;
const num = (value: number, digits = 1): string => value.toLocaleString("ru-RU", { maximumFractionDigits: digits });
const week = (key: string, number: number, year: number): string => `неделя ${number} (${key}, ${year})`;

const VERDICT: Record<DetailsVerdict, string> = {
  cheap: "Прятать «Влияние» и «Цифру» под «Добавить детали» дёшево: их почти не заполняют. Решение 14 можно делать как принято",
  discuss: "Доля посередине: решение 14 стоит обсудить заново, прежде чем прятать поля",
  revisit: "Поля заполняют часто: решение 14 надо пересматривать, прятать их под «Добавить детали» дорого",
};

const REASON: Record<MoveReason, string> = {
  section: "сдана по этому блоку шаблона",
  sense: "по смыслу",
  products: "блока по смыслу в шаблоне нет: ушла в «Продукты»",
  first: "ни блока по смыслу, ни «Продуктов»: ушла в первый блок шаблона",
};

const FLAG: Record<MoveFlag, string> = {
  "stale-section": "блока, по которому запись сдали, в шаблоне уже нет: блок записи теряется",
  "outside-template": "запись переезжает в блок, которого в шаблоне её команды нет: шаблона у команды нет совсем, блок считали по стандартному набору из восьми блоков (решение 5)",
  "figures-block": "блок цифр: его ресурс собирает сам, строка записи там не сохранится",
  "no-author": "у записи нет автора: команды и шаблона у неё нет",
  "split-teams": "человек в нескольких командах: в их отчётах запись попадёт в разные блоки",
};

const moveLine = (m: Move): string[] => [
  `  ${m.weekKey}, ${m.author}${m.team ? `, команда «${m.team}»` : ", команды с шаблоном нет"}: «${m.fromLabel}» → «${m.toTitle}» (${REASON[m.reason]})`,
  `    начало записи: ${m.start}${m.start.length >= 40 ? "..." : ""}`,
  ...m.flags.map((f) => `    ! ${FLAG[f]}`),
  ...(m.perTeam.length > 1 || m.perTeam.some((p) => !p.inTemplate)
    ? [`    по командам: ${m.perTeam.map((p) => `«${p.team}» → «${p.toTitle}»${p.inTemplate ? "" : " (такого блока в шаблоне команды нет)"}`).join(", ")}`]
    : []),
];

/** Весь замер текстом: пять ответов по порядку вопросов документа решений */
export function surveyText(s: Survey, now = new Date()): string {
  const out: string[] = [];
  const add = (...lines: string[]) => out.push(...lines);
  const first = s.input.weeks[s.input.weeks.length - 1];
  const last = s.input.weeks[0];

  add(
    "Замер живых данных перед пересборкой экрана «Сдать weekly» (этап 87)",
    `Снято: ${now.toLocaleString("ru-RU", { timeZone: "Europe/Moscow" })} по Москве. Только чтение: в базу ничего не записано.`,
    last && first ? `Период: ${s.input.weeks.length} недель, с ${first.key} по ${last.key}. Подробно последние ${s.input.recent}.` : "Недель в базе нет: замерять нечего.",
    "В выводе есть имена людей и названия команд: без них пункты 4 и 5 не прочитать. Файл с выводом не коммитить и не выкладывать.",
    "",
  );
  if (!last) return out.join("\n");

  // 1. Записи и поля
  add(
    "1. Сколько записей сдают за неделю и какие поля заполняют",
    `Записей за период: ${s.fills.entries}. В среднем за неделю: ${num(s.fills.perWeek)} (по ${s.fills.countedWeeks} завершённым неделям; текущая отчётная неделя в среднее не идёт, она неполная).`,
    "Записи по неделям:",
    ...s.fills.byWeek.map((w) => `  ${week(w.week.key, w.week.number, w.week.year)}: ${w.entries}${w.week.current ? " (текущая, неделя не закончилась)" : ""}`),
    `Поля заполнены (за все ${s.input.weeks.length} недель):`,
    ...s.fills.fields.map((f) => `  ${f.title}: ${f.filled} из ${s.fills.entries}, ${pct(f.share)}`),
    `Те же поля по каждой из последних ${s.input.recent} недель: видно, меняется ли привычка.`,
  );
  for (const w of s.fills.recent) {
    add(`  ${week(w.week.key, w.week.number, w.week.year)}, записей ${w.entries}: ${w.fields.map((f) => `${f.title} ${pct(f.share)}`).join(", ")}`);
  }
  add(
    "Что это значит для решения 14 (прятать «Влияние», «Цифру», ссылку и «Помощь» под «Добавить детали»):",
    "  порог из документа решений: ниже 15% — прятать дёшево; от 15% до 40% — решение обсудить заново; выше 40% — решение надо пересматривать.",
    `  ${VERDICT[s.fills.verdict]}.`,
    "",
  );

  // 2. Шаблоны блоков
  add("2. Сколько команд завели шаблон блоков");
  if (!s.templates.withTemplate) {
    add(
      `Шаблон не завела ни одна команда из ${s.templates.teamsTotal} включённых (топ-команда не считается: по коду шаблона у неё нет).`,
      "Миграция и переезд ленты проще: по решению 5 всем командам выдаётся стандартный набор из восьми блоков, и записи поедут по нему.",
    );
  } else {
    add(`Шаблон есть у ${s.templates.withTemplate} команд из ${s.templates.teamsTotal}. Своих блоков (не из стандартного набора) всего: ${s.templates.customTotal}.`);
    for (const r of s.templates.rows) {
      add(`  «${r.team}»: блоков ${r.blocks}${r.custom.length ? `, свои: ${r.custom.map((c) => `«${c}»`).join(", ")}` : ", своих нет"}${r.noProducts ? '. В шаблоне нет блока «Продукты»: записи поедут не по смыслу' : ""}${r.onlyFigures ? ". В шаблоне только блоки цифр: записям в нём места нет" : ""}`);
    }
  }
  add("");

  // 3. Обрезка строки отчёта
  add(
    `3. Обрезка строки отчёта на ${s.cut.limit} знаках (BLOCK_LIMITS.text)`,
    `Проверено записей: ${s.cut.checked}. Не влезает в предел: ${s.cut.cut} (${pct(s.cut.share)}). Самая длинная строка: ${s.cut.longest} знаков.`,
    "Строка отчёта это «Что произошло» плюс «Цифра или факт», а если цифры нет — «Влияние на бизнес». «Что произошло»",
    "не длиннее 150 знаков: предел стоит и в базе. На «Влияние» (предел формы 500), «Цифру» (300), «Что дальше» (500) и",
    "«Помощь» (300) проверок в базе нет, их держит только форма, поэтому загруженные записи могут быть и длиннее.",
    "Поэтому в 600 знаков не влезает прежде всего запись с длинным «Влиянием» и пустой «Цифрой»: 150 + 2 + 500 = 652.",
  );
  if (!s.cut.cut) add("Ни одна запись за период в предел не упирается: трогать предел незачем.");
  for (const e of s.cut.examples) {
    add(
      `  ${e.weekKey}, ${e.author}: было ${e.before} знаков, стало ${e.after}`,
      `    до обрезки: ${e.full}`,
      `    после обрезки: ${e.cut}`,
    );
  }
  add("");

  // 4. Человек в нескольких командах
  add("4. Люди в двух и более командах с разными шаблонами");
  if (!s.multi.people.length) {
    add("Таких людей нет: ни у кого нет двух команд с разными шаблонами.");
  } else {
    add(
      `Таких людей: ${s.multi.people.length}.`,
      "Правило приложения (templateForAuthor): человек получает не «шаблон первой команды», а шаблон первой команды из списка, где шаблон задан;",
      "в начале списка идут команды, которые ждут его weekly, затем остальные его команды. Одна запись сдаётся по одному шаблону.",
      `Расхождений со «шаблоном первой команды»: ${s.multi.notFirst}.`,
    );
    for (const p of s.multi.people) {
      add(
        `  ${p.name}: ${p.teams.map((t) => `«${t.name}» (${t.blocks === null ? "шаблона нет" : `блоков ${t.blocks}`})`).join(" → ")}`,
        `    получает: ${p.winner ? `шаблон команды «${p.winner}»: ${p.blocks.join(", ")}` : "шаблона нет ни в одной команде, запись раскладывается по смыслу"}`,
        ...(p.notFirst ? ["    ! расхождение: первая команда в списке без шаблона, правило взяло следующую"] : []),
      );
    }
  }
  add("");

  // 5. Выборка миграции
  add(
    `5. Выборка миграции за ${s.move.weeks.length} недель (решение 8: необратимый шаг, выборку утверждает владелец)`,
    `Недели выборки: ${s.move.weeks.join(", ")}. Записей в выборке: ${s.move.entries}.`,
    "Блок считается по шаблону той команды, по которой человек сдаёт weekly (правило templateForAuthor); шаблона нет —",
    "по стандартному набору из восьми блоков (решение 5). В отчёте другой его команды та же запись может попасть в другой",
    "блок: такие случаи помечены ниже.",
    "Куда переезжают записи:",
    ...s.move.targets.map((t) => `  «${t.toTitle}»: ${t.count}`),
    "Было и стало:",
    ...s.move.pairs.map((p) => `  «${p.fromLabel}» → «${p.toTitle}»: ${p.count}`),
    "Почему именно туда:",
    `  сдана по блоку шаблона: ${s.move.byReason.section}`,
    `  по смыслу: ${s.move.byReason.sense}`,
    `  блока по смыслу в шаблоне нет, ушла в «Продукты»: ${s.move.byReason.products}`,
    `  ни блока по смыслу, ни «Продуктов», ушла в первый блок шаблона: ${s.move.byReason.first}`,
  );
  if (!s.move.problems.length) {
    add("Спорных случаев нет: правило по каждой записи дало однозначный ответ, и каждая запись попала в блок шаблона своей команды.");
  } else {
    add(`Спорные случаи: ${s.move.problems.length} из ${s.move.entries}. Именно они решают, можно ли утверждать миграцию:`);
    for (const m of s.move.problems) add(...moveLine(m));
  }
  add("", `Итог: ${s.move.problems.length ? `разобрать ${s.move.problems.length} спорных случаев выше и только после этого утверждать миграцию` : "выборку можно утверждать: спорных случаев нет"}.`);
  return out.join("\n");
}
