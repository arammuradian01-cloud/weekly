/** Строки, по которым в имитации есть факт Weekly: итоги и каналы, как в настоящей вкладке «Факт Weekly для приложения» */
export const IMITATION_FACT_IDS = ["OS.TOT.S", "OS.TOT.R", "OS.CH.B2C.S", "OS.CH.B2B.S", "OS.CH.B2C.R", "OS.CH.B2B.R", "MI.TOT.S", "MI.TOT.R", "DE.TOT.R", "DE.B2C.K"];

export const IMITATION_FIRST_WEEK = "2026-09-28";
export const IMITATION_FIRST_DAY = "2026-10-01";
export const IMITATION_LAST_DAY = "2027-12-31";
export const IMITATION_WEEKS = 66;

/** Сезонность недели: плавная волна, у каждой недели свой множитель */
const season = (j: number) => 1 + 0.08 * Math.sin(j / 5);
const lrf = (id: string) => (id.startsWith("OS.") ? 1.04 : 0.97);
/** Факт против бюджета: детерминированный разброс ±8% */
const factMul = (id: string, j: number) => 0.94 + (((j * 7 + id.length * 3) % 17) / 17) * 0.12;

const monthOf = (day: string) => `${day.slice(0, 7)}-01`;

/** Части недели по месяцам: [месяц, дней в части] в пределах плана */
export function weekParts(week: string): [string, number][] {
  const out: [string, number][] = [];
  for (let d = 0; d < 7; d++) {
    const day = addDays(week, d);
    if (day < IMITATION_FIRST_DAY || day > IMITATION_LAST_DAY) continue;
    const m = monthOf(day);
    const last = out.at(-1);
    if (last && last[0] === m) last[1] += 1;
    else out.push([m, 1]);
  }
  return out;
}

export function imitationWeeks(): string[] {
  return Array.from({ length: IMITATION_WEEKS }, (_, j) => addDays(IMITATION_FIRST_WEEK, 7 * j));
}

