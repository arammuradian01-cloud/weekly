function planGrid(): Grid {
  const rows: Grid = [];
  const weeks = imitationWeeks();
  for (const version of ["Бюджет", "LRF"]) {
    for (const l of IMITATION_LINES) {
      const mul = version === "LRF" ? lrf(l[0]) : 1;
      const keys = [l[1], l[2], l[3], l[4], l[5], l[6], l[7], l[8]];
      if (l[2] === "только месяц") {
        for (let m = "2026-10-01"; m <= "2027-12-01"; m = nextMonth(m)) rows.push([l[0], version, m < "2027-01-01" ? "LBE" : "план", "", "", m, "месяц", ...keys, Math.round(20 * mul * 1000) / 1000, "открыто"]);
        continue;
      }
      weeks.forEach((w, j) => {
        const perDay = (l[10] * season(j) * mul) / 7;
        weekParts(w).forEach(([m, days], p) => rows.push([l[0], version, m < "2027-01-01" ? "LBE" : "план", w, addDays(w, 6), m, p + 1, ...keys, Math.round(perDay * days * 1000) / 1000, "открыто"]));
      });
    }
  }
  return [
    ["План для DWH: бюджет и LRF по неделям и месяцам (имитация)"],
    ["Зерно: line_id x версия x часть недели"],
    ["Проверка: сумма плана минус сумма вкладок недель", "Бюджет", 0, "LRF", 0, "ок", `строк: ${rows.length}`],
    ["line_id", "Версия", "Статус", "Неделя с", "Неделя по", "Месяц", "Часть", "Продукт", "Срез", "Канал", "Контрагент", "Регион", "Тип продажи", "Показатель", "Ед.", "Значение", "Доступ"],
    ...rows,
  ];
}

/** Факт Weekly за закрытые недели до today (неделя кончилась до этого дня) */
function factGrid(today: string): Grid {
  const rows: Grid = [["line_id", "week_start", "value", "updated_at", "source"]];
  const weeks = imitationWeeks();
  for (const id of IMITATION_FACT_IDS) {
    const l = IMITATION_LINES.find((x) => x[0] === id)!;
    weeks.forEach((w, j) => {
      const closed = addDays(w, 6) < today;
      const days = weekParts(w).reduce((s, [, d]) => s + d, 0);
      // Неделя 28.09: факт за все 7 дней (Weekly считает неделю целиком), план только за 1-4 октября
      const value = closed ? Math.round(((l[10] * season(j)) / 7) * Math.max(days, 7) * factMul(id, j) * 1000) / 1000 : "";
      rows.push([id, w, value, closed ? today : "", "Weekly Sravni"]);
    });
  }
  return rows;
}

/** Листы таблицы недель в имитации: справочник, план и факт Weekly на день today */
export function weekPlanImitation(today: string): Record<string, Grid> {
  return { [WEEKPLAN_TABS.dict]: dictGrid(), [WEEKPLAN_TABS.plan]: planGrid(), [WEEKPLAN_TABS.appFact]: factGrid(today) };
}
