// Короткий текст одной-двумя фразами (этап 28, с этапа 76 общий модуль): названия инициатив, ответы оценки встреч.
// Длинное тире и стрелки заменяются на дефис, пробелы и переносы строк схлопываются, длина ограничена

/** Одна строка без длинного тире и стрелок, не длиннее max знаков */
export function cleanPhrase(text: unknown, max: number): string {
  return String(text ?? "")
    .replace(/[—–→⟶⇒]/g, "-")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, max);
}
