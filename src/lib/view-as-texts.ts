// Тексты отказа режима «Смотреть как» (этап 63) и входа владельца в чужой профиль (этап 71) без зависимостей: их берут
// и сервер, и экраны (отправка черновиков с устройства отличает по ним отказ входа от отказа правила).

/** Ответ на любое изменение в режиме просмотра */
export const VIEW_AS_DENIED = "В режиме «Смотреть как» изменения недоступны";
/** Ответ на изменение из вкладки, которая осталась от закончившегося просмотра */
export const VIEW_AS_ENDED = "Просмотр закончился, обновите страницу";

/**
 * Этап 71: изменение из вкладки, которую сервер показал для другого профиля: владелец вошёл в чужой профиль или
 * вернулся в свой в другой вкладке. Правка ушла бы не от того имени
 */
export const OWNER_AS_STALE = "Профиль на этом устройстве сменился, обновите страницу";
/** Этап 71: вход владельца в чужой профиль закончился сам (срок, человека выключили), а владелец ещё не вернулся к себе */
export const OWNER_AS_ENDED = "Вход в профиль другого человека закончился, вернитесь в свой профиль";

/**
 * Отказ входа, а не правила: повтор после выхода из просмотра или после обновления страницы пройдёт, черновик не
 * выбрасываем. Имя осталось от этапа 63, отказы входа владельца в чужой профиль (этап 71) тоже здесь
 */
export function isViewAsRefusal(error: string): boolean {
  return error === VIEW_AS_DENIED || error === VIEW_AS_ENDED || error === OWNER_AS_STALE || error === OWNER_AS_ENDED;
}
