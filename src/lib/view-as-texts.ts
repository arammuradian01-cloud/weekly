// Тексты отказа режима «Смотреть как» (этап 63) без зависимостей: их берут и сервер, и экраны (отправка черновиков
// с устройства отличает по ним отказ просмотра от отказа правила).

/** Ответ на любое изменение в режиме просмотра */
export const VIEW_AS_DENIED = "В режиме «Смотреть как» изменения недоступны";
/** Ответ на изменение из вкладки, которая осталась от закончившегося просмотра */
export const VIEW_AS_ENDED = "Просмотр закончился, обновите страницу";

/** Отказ просмотра, а не правила: повтор после выхода из просмотра пройдёт, черновик не выбрасываем */
export function isViewAsRefusal(error: string): boolean {
  return error === VIEW_AS_DENIED || error === VIEW_AS_ENDED;
}
