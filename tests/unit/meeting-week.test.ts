// Этап 73б: на какой неделе открывается встреча. Отчётная неделя меняется во вторник в 18:00 по Москве, через сутки
// после срока сдачи; идущая встреча команды держит свою неделю; явный выбор сохраняется, будущая неделя не открывается.
import { describe, expect, it } from "vitest";
import { meetingWeekKey, weekNumberOf, weekYearOf } from "@/lib/weekly/weeks";
import type { WeekKey } from "@/domain/types";

const deadline = { weekday: 1, time: "18:00" };
// Москва живёт в UTC+3: так в таблице московское время, а не время машины
const msk = (local: string) => new Date(`${local}+03:00`);

type Row = { name: string; now: string; requested?: string; live?: WeekKey[]; want: WeekKey };

const rows: Row[] = [
  { name: "понедельник: срок сдачи сегодня, встреча завтра, отчётная прошлая неделя", now: "2026-10-26T12:00:00", want: "2026-10-19" },
  { name: "понедельник после срока сдачи: всё ещё прошлая", now: "2026-10-26T20:00:00", want: "2026-10-19" },
  { name: "вторник 17:59:59: встреча идёт по прошлой неделе", now: "2026-10-27T17:59:59", want: "2026-10-19" },
  { name: "вторник 18:00:01: отчётной стала текущая", now: "2026-10-27T18:00:01", want: "2026-10-26" },
  { name: "смена года, вторник 17:59:59: 2026-W53", now: "2027-01-05T17:59:59", want: "2026-12-28" },
  { name: "смена года, вторник 18:00:01: 2027-W01", now: "2027-01-05T18:00:01", want: "2027-01-04" },
  { name: "будущая неделя заменяется отчётной", now: "2026-10-26T12:00:00", requested: "2026-11-02", want: "2026-10-19" },
  { name: "календарная текущая неделя до вторника 18:00 ещё будущая", now: "2026-10-27T17:59:59", requested: "2026-10-26", want: "2026-10-19" },
  { name: "явно выбранная прошлая неделя остаётся", now: "2026-10-27T18:00:01", requested: "2026-09-28", want: "2026-09-28" },
  { name: "явно выбранная отчётная неделя остаётся", now: "2026-10-27T18:00:01", requested: "2026-10-26", want: "2026-10-26" },
  { name: "не понедельник: отчётная", now: "2026-10-27T18:00:01", requested: "2026-10-27", want: "2026-10-26" },
  { name: "мусор вместо недели: отчётная", now: "2026-10-27T18:00:01", requested: "abc", want: "2026-10-26" },
  { name: "идущая встреча после вторника 18:00 держит свою неделю", now: "2026-10-27T18:30:00", live: ["2026-10-19"], want: "2026-10-19" },
  { name: "встреча в четверг (слот week:1) идёт по прошлой неделе", now: "2026-10-29T11:00:00", live: ["2026-10-19"], want: "2026-10-19" },
  { name: "идущая встреча отчётной недели", now: "2026-11-03T10:00:00", live: ["2026-10-26"], want: "2026-10-26" },
  { name: "из двух идущих берём позднюю", now: "2026-10-29T11:00:00", live: ["2026-10-26", "2026-10-19"], want: "2026-10-26" },
  { name: "забытая открытой давняя встреча не уводит в прошлое", now: "2026-10-29T11:00:00", live: ["2026-09-28"], want: "2026-10-26" },
  { name: "идущая встреча на смене года", now: "2027-01-05T18:30:00", live: ["2026-12-28"], want: "2026-12-28" },
  { name: "явный выбор важнее идущей встречи", now: "2026-10-29T11:00:00", requested: "2026-10-12", live: ["2026-10-19"], want: "2026-10-12" },
  { name: "будущая неделя при идущей встрече: неделя встречи", now: "2026-10-29T11:00:00", requested: "2026-11-09", live: ["2026-10-19"], want: "2026-10-19" },
];

describe("неделя встречи", () => {
  it.each(rows)("$name", ({ now, requested, live, want }) => {
    expect(meetingWeekKey({ now: msk(now), deadline, requested, live })).toBe(want);
  });

  it("номера недель на смене года: 53 неделя 2026 и 1 неделя 2027", () => {
    expect([weekYearOf("2026-12-28"), weekNumberOf("2026-12-28")]).toEqual([2026, 53]);
    expect([weekYearOf("2027-01-04"), weekNumberOf("2027-01-04")]).toEqual([2027, 1]);
  });

  it("свой срок сдачи: во вторник до 12:00, отчётная меняется в среду в 12:00", () => {
    const tuesday = { weekday: 2, time: "12:00" };
    expect(meetingWeekKey({ now: msk("2026-10-28T11:59:59"), deadline: tuesday })).toBe("2026-10-19");
    expect(meetingWeekKey({ now: msk("2026-10-28T12:00:01"), deadline: tuesday })).toBe("2026-10-26");
  });
});
