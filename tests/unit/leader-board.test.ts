describe("какие вкладки читаются", () => {
  it("только вкладки целей: зарплаты, мотивация, калибровка, старые и копии не читаются", () => {
    expect(isGoalsTab("Цели CPO")).toBe(true);
    expect(isGoalsTab("Цели бизнес")).toBe(true);
    expect(isGoalsTab("INS CPO_новая")).toBe(false);
    expect(isGoalsTab("Цели и мотивация")).toBe(false);
    expect(isGoalsTab("Цели и мотивация (копия)")).toBe(false);
    expect(isGoalsTab("Цели PO - old")).toBe(false);
    expect(isGoalsTab("Калибровка h1/26")).toBe(false);
    const salary = { name: "INS CPO_новая", grid: [["Сотрудник", "Заработная плата"], ["Токов Никита", "р.400 000"]] };
    const out = readLeaderBoard([salary, cpo, { name: "Цели и мотивация", grid: [["Gross Salary", "330 000"]] }], 4);
    expect(out.map((t) => t.tab)).toEqual(["Цели CPO"]);
    expect(JSON.stringify(out)).not.toMatch(/400 000|330 000|Salary|плата/);
  });

  it("владелец из шапки: «роль - имя», просто имя; «На кого???» и «в поисках»: нет владельца", () => {
    expect(ownerOf(cpo.grid)).toBe("Рева Тарас");
    expect(ownerOf(golovkin.grid)).toBe("Влад Головкин");
    expect(ownerOf([["На кого???", "Еще не утвердили"]])).toBeNull();
    expect(ownerOf([["Алсу До Q2, с Q3 нет BDM - в поисках"]])).toBeNull();
    expect(ownerOf([["https://docs.google.com/spreadsheets/d/abc"]])).toBeNull();
  });
});

describe("раздел квартала", () => {
  it("берётся только раздел 4Q до договорённостей; строки без номера получают следующий номер", () => {
    const t = readLeaderTab(cpo, 4);
    expect(t.skip).toBeNull();
    expect(t.goals.map((g) => [g.number, g.title])).toEqual([
      [1, "Цели 2027 поставлены каждому лидеру"],
      [2, "Предстраховой скоринг - стратегия"],
      [3, "Досбор согласий на рекламу"],
    ]);
    expect(t.goals[0]!.description).toBe("Направление: Strategy.\nЧто ожидаю:\n1. До 17.10 с каждым");
    expect(t.goals[2]).toMatchObject({ base: "30%", target: "40%" });
    // Третий квартал из той же вкладки
    expect(readLeaderTab(cpo, 3).goals.map((g) => g.title)).toEqual(["Цель третьего квартала"]);
  });

  it("шапка вида «4 Q 2026» рядом с «Запланировано»: направление под подписью квартала", () => {
    const t = readLeaderTab(golovkin, 4);
    expect(t.goals.map((g) => [g.number, g.direction, g.title, g.target, g.base])).toEqual([
      [1, "Bussines", "Согласовать план 2027 со страховыми", "есть >1 игрок", "0"],
      [4, "Дебиторка", "Дебиторка не выше 40% оборота", "просрочка 0", "68%"],
    ]);
  });

  it("борд Depo: строки без номера и пустые номера, ячейка в кавычках с табуляцией", () => {
    const t = readLeaderTab(depo, 4);
    expect(t.goals.map((g) => [g.number, g.title])).toEqual([
      [1, "Выполнение финансовых показателей"],
      [2, "Составить портрет вкладчика"],
    ]);
    expect(t.goals[0]!.target).toBe("target PRODUCT REVENUE 29 250 000");
  });

  it("нет раздела, пустой раздел, нет владельца: вкладка пропускается с причиной", () => {
    expect(readLeaderTab({ name: "Цели X", grid: [["Иванов Пётр"], ["№", "Направление", "Запланировано на 3Q"]] }, 4).skip).toMatch(/Нет раздела/);
    expect(readLeaderTab({ name: "Цели X", grid: [["Иванов Пётр"], ["№", "Направление", "Запланировано на 4Q"], ["1"], ["2"]] }, 4).skip).toMatch(/пустой/);
    expect(readLeaderTab({ name: "Цели X", grid: [["На кого???"], ["№", "Направление", "Запланировано на 4Q"], ["1", "", "Цель"]] }, 4).skip).toMatch(/не указан владелец/);
  });

  it("один владелец в двух вкладках: вторая пропускается, шапку стоит проверить", () => {
    const back = { name: "Цели Lead Back Red", grid: [["Lead Back Red - Красноперов Алексей"], ["№", "Направление", "Запланировано на 4Q"], ["1", "", "Бэкенд"]] };
    const front = { name: "Цели Lead Front Red", grid: [["Lead Back Red - Алексей Красноперов"], ["№", "Направление", "Запланировано на 4Q"], ["1", "", "Фронт"]] };
    const out = readLeaderBoard([back, front], 4);
    expect(out[0]!.skip).toBeNull();
    expect(out[1]!.skip).toMatch(/уже есть во вкладке «Цели Lead Back Red»/);
  });
});

describe("тексты и коды", () => {
  it("длинное название: первая фраза до 300 знаков, остальное в описание", () => {
    const long = `${"Короткая первая фраза про цель квартала. ".repeat(3)}${"Подробности ".repeat(40)}`;
    const { title, rest } = splitTitle(long);
    expect(title.length).toBeLessThanOrEqual(300);
    expect(title.endsWith(".")).toBe(true);
    expect(`${title} ${rest}`.replace(/\s+/g, " ").trim()).toBe(long.replace(/\s+/g, " ").trim());
    expect(splitTitle("Короткая цель")).toEqual({ title: "Короткая цель", rest: "" });
  });

  it("код цели человека: инициалы и номер", () => {
    expect(personCode("Рева Тарас", 1)).toBe("РТ-1");
    expect(personCode("Чейченец Евгений Игоревич", 12)).toBe("ЧЕ-12");
  });
});
