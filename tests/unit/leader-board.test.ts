describe("тексты и коды", () => {
  it("длинное название: первая фраза до 300 знаков, остальное в описание", () => {
    const long = `${"Короткая первая фраза про цель квартала. ".repeat(3)}${"Подробности ".repeat(40)}`;
    const { title, rest } = splitTitle(long);
    expect(title.length).toBeLessThanOrEqual(300);
    expect(title.endsWith(".")).toBe(true);
    expect(`${title} ${rest}`.replace(/\s+/g, " ").trim()).toBe(long.replace(/\s+/g, " ").trim());
    expect(splitTitle("Короткая цель")).toEqual({ title: "Короткая цель", rest: "" });
  });

  it("код цели человека: инициалы и номер", () => {
    expect(personCode("Рева Тарас", 1)).toBe("РТ-1");
    expect(personCode("Чейченец Евгений Игоревич", 12)).toBe("ЧЕ-12");
  });

  it("основа кода: инициалы заняты, фамилия; фамилия тоже, фамилия с инициалом; длинная фамилия укорочена", () => {
    const taken = new Set<string>();
    expect(codeBase("Иванов Пётр", (b) => taken.has(b))).toBe("ИП");
    taken.add("ИП");
    expect(codeBase("Иванов Павел", (b) => taken.has(b))).toBe("Иванов");
    taken.add("Иванов");
    expect(codeBase("Иванов Пётр Сергеевич", (b) => taken.has(b))).toBe("ИвановП");
    taken.add("ИвановП");
    expect(codeBase("Иванов Платон", (b) => taken.has(b))).toBe("ИП2");
    const long = codeBase("Константинопольская Анна", (b) => b === "КА");
    expect(`${long}-12`.length).toBeLessThanOrEqual(20);
  });

  it("номера при загрузке: «№» остаётся, строка без номера получает номер прежней цели с тем же названием", () => {
    const g = (title: string, number: number, numbered = false): LeaderGoal => ({ number, numbered, title, direction: "", description: "", base: "", target: "" });
    // Было: А-1, Б-2 без номеров. В середину вставили В: Б сохраняет 2, В получает свободный номер
    expect(assignNumbers([g("А", 1), g("В", 2), g("Б", 3)], new Map([["а", 1], ["б", 2]]))).toEqual([1, 3, 2]);
    // Номер из колонки сильнее названия
    expect(assignNumbers([g("А", 5, true), g("Б", 6)], new Map([["б", 5]]))).toEqual([5, 6]);
  });
});
