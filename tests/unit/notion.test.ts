// Этап 23: разбор текста разбора встречи из Notion в кандидатов.
import { describe, expect, it } from "vitest";
import { parseNotion } from "@/lib/meeting/notion";

describe("приём из Notion", () => {
  it("списки становятся задачами, «решили» решениями, имя и срок распознаются", () => {
    const text = `# Разбор встречи 13.10
Итоги:
- Решили: запускаем КАСКО для такси в ноябре
- @Логинова прислать выгрузку по убыткам до пятницы
- Тарас: собрать требования к новому скорингу к 20.10
• Договорились не трогать тарифы ОСАГО до конца месяца
1. Подготовить презентацию для CEO
[ ] Проверить интеграцию с СК
ok`;
    const out = parseNotion(text);
    expect(out.map((c) => [c.kind, c.text, c.who ?? null, c.due ?? null])).toEqual([
      ["decision", "запускаем КАСКО для такси в ноябре", null, null],
      ["task", "прислать выгрузку по убыткам до пятницы", "Логинова", "до пятницы"],
      ["task", "собрать требования к новому скорингу к 20.10", "Тарас", "к 20.10"],
      ["decision", "не трогать тарифы ОСАГО до конца месяца", null, "до конца месяца"],
      ["task", "Подготовить презентацию для CEO", null, null],
      ["task", "Проверить интеграцию с СК", null, null],
    ]);
  });

  it("пустой текст, заголовки и короткие строки пропускаются, длинное тире заменяется", () => {
    expect(parseNotion("")).toEqual([]);
    expect(parseNotion("Повестка:\n\n## Риски\n- ок")).toEqual([]);
    expect(parseNotion("- Сверить цифры — по всем линиям")[0]!.text).toBe("Сверить цифры - по всем линиям");
  });
});
